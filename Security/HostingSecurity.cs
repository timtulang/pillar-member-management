using System.Net;
using System.Security.Cryptography;
using System.Security.Cryptography.X509Certificates;
using Microsoft.AspNetCore.DataProtection;
using Microsoft.AspNetCore.DataProtection.KeyManagement;
using Microsoft.AspNetCore.HttpOverrides;

namespace Pillar.Security;

public static class HostingSecurity
{
    public static bool IsVercel(IConfiguration config) =>
        string.Equals(config["Security:HostingPlatform"], "Vercel", StringComparison.OrdinalIgnoreCase);

    public static void ConfigureProxy(ForwardedHeadersOptions options, IConfiguration config)
    {
        options.ForwardedHeaders = ForwardedHeaders.XForwardedFor | ForwardedHeaders.XForwardedProto;
        options.ForwardLimit = 1;
        if (IsVercel(config))
        {
            // Opt-in only for a private Vercel container behind its managed ingress.
            // Vercel overwrites these headers. Never use this mode for a directly exposed server.
            options.KnownProxies.Clear();
            options.KnownIPNetworks.Clear();
        }
        else
        {
            foreach (var proxy in config.GetSection("Security:TrustedProxies").Get<string[]>() ?? [])
                options.KnownProxies.Add(IPAddress.Parse(proxy));
        }
    }

    public static void AddKeyStorage(IServiceCollection services, IConfiguration config, bool development)
    {
        var protection = services.AddDataProtection().SetApplicationName("Pillar.MemberManagement");
        var store = config["Security:DataProtectionStore"] ?? "FileSystem";
        if (IsVercel(config) && !string.Equals(store, "Database", StringComparison.OrdinalIgnoreCase))
            throw new InvalidOperationException("Vercel requires Security__DataProtectionStore=Database. Its container filesystem is not persistent.");
        if (string.Equals(store, "Database", StringComparison.OrdinalIgnoreCase))
        {
            var certificate = LoadCertificate(config["Security:DataProtectionCertificate"], config["Security:DataProtectionCertificatePassword"], true);
            var previous = config.GetSection("Security:DataProtectionPreviousCertificates").GetChildren()
                .Select(c => LoadCertificate(c["Certificate"], c["Password"], false)).ToArray();
            services.AddSingleton<PostgresKeyRepository>();
            services.AddOptions<KeyManagementOptions>().Configure<PostgresKeyRepository>((options, repository) => options.XmlRepository = repository);
            protection.ProtectKeysWithCertificate(certificate).UnprotectKeysWithAnyCertificate([certificate, .. previous]);
        }
        else if (string.Equals(store, "FileSystem", StringComparison.OrdinalIgnoreCase))
        {
            var path = config["Security:DataProtectionKeyPath"];
            if (!string.IsNullOrWhiteSpace(path)) protection.PersistKeysToFileSystem(new DirectoryInfo(path));
            else if (!development) throw new InvalidOperationException("Set Security__DataProtectionStore=Database, or set Security__DataProtectionKeyPath to a private persistent directory.");
        }
        else throw new InvalidOperationException("Security__DataProtectionStore must be Database or FileSystem.");
    }

    private static X509Certificate2 LoadCertificate(string? encoded, string? password, bool encrypting)
    {
        if (string.IsNullOrWhiteSpace(encoded) || string.IsNullOrWhiteSpace(password))
            throw new InvalidOperationException("Database key storage requires Security__DataProtectionCertificate and Security__DataProtectionCertificatePassword. See docs/VERCEL.md.");
        X509Certificate2 certificate;
        try
        {
            certificate = X509CertificateLoader.LoadPkcs12(Convert.FromBase64String(encoded), password.TrimEnd('\r', '\n'), X509KeyStorageFlags.EphemeralKeySet);
        }
        catch (Exception e) when (e is FormatException or CryptographicException)
        { throw new InvalidOperationException("The data-protection certificate or its password is invalid. Use the two files generated by scripts/create-protection-certificate.sh."); }
        using var rsa = certificate.GetRSAPrivateKey();
        if (rsa == null || rsa.KeySize < 2048)
            throw new InvalidOperationException("The data-protection certificate must include an RSA private key of at least 2048 bits.");
        if (encrypting && (certificate.NotBefore.ToUniversalTime() > DateTime.UtcNow || certificate.NotAfter.ToUniversalTime() <= DateTime.UtcNow))
            throw new InvalidOperationException("The data-protection certificate is not currently valid. See the certificate rotation instructions in docs/VERCEL.md.");
        return certificate;
    }
}
